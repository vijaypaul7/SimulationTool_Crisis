def identify_energy_shocks(df, fuel_col='petrol_price',
                           threshold_method='percentile',
                           threshold_value=90):
    """
    Identify energy shock months in the dataset.

    Parameters:
    -----------
    df : DataFrame with fuel price data
    fuel_col : str, column name for fuel prices
    threshold_method : str, 'percentile' or 'std'
    threshold_value : float, percentile (90) or number of std deviations (2)

    Returns:
    --------
    df : DataFrame with shock indicators added
    shock_summary : dict with shock statistics
    """

    # Calculate month-on-month growth rate
    df['fuel_price_mom_pct'] = df[fuel_col].pct_change() * 100

    # Clean infinite values
    df['fuel_price_mom_pct'] = df['fuel_price_mom_pct'].replace([np.inf, -np.inf], np.nan)

    # Identify shocks based on method
    if threshold_method == 'percentile':
        threshold = df['fuel_price_mom_pct'].dropna().quantile(threshold_value / 100)
        df['fuel_price_shock'] = (df['fuel_price_mom_pct'] > threshold).astype(int)
        shock_label = f'Top {100 - threshold_value}% MoM increases'

    elif threshold_method == 'std':
        mean = df['fuel_price_mom_pct'].dropna().mean()
        std = df['fuel_price_mom_pct'].dropna().std()
        threshold = mean + (threshold_value * std)
        df['fuel_price_shock'] = (df['fuel_price_mom_pct'] > threshold).astype(int)
        shock_label = f'>{threshold_value} std deviations above mean'

    # Also identify extreme negative shocks (price drops)
    if threshold_method == 'percentile':
        lower_threshold = df['fuel_price_mom_pct'].dropna().quantile((100 - threshold_value) / 100)
        df['fuel_price_drop_shock'] = (df['fuel_price_mom_pct'] < lower_threshold).astype(int)

    # Calculate shock statistics
    shock_months = df[df['fuel_price_shock'] == 1]['month'].tolist()
    shock_count = len(shock_months)
    total_months = len(df)
    shock_pct = (shock_count / total_months) * 100

    shock_summary = {
        'shock_months': shock_months,
        'shock_count': shock_count,
        'total_months': total_months,
        'shock_percentage': shock_pct,
        'threshold': threshold,
        'shock_label': shock_label,
        'mean_shock_increase': df[df['fuel_price_shock'] == 1]['fuel_price_mom_pct'].mean(),
        'max_shock_increase': df[df['fuel_price_shock'] == 1]['fuel_price_mom_pct'].max()
    }

    return df, shock_summary

