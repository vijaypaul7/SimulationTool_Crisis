# Function to compute lagged correlations
def compute_lagged_correlations(df, target, variable, max_lag=12):
    lags = range(-max_lag, max_lag + 1)
    correlations = []
    for lag in lags:
        if lag < 0:
            corr = df[target].corr(df[variable].shift(-lag))
        else:
            corr = df[target].shift(lag).corr(df[variable])
        correlations.append(corr)
    return lags, correlations

