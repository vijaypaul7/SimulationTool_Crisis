# 13. TRAINING-ONLY FEATURE SCREENING
# =============================================================================

def screen_features(
    X_train,
    X_test,
    max_missing=MAX_MISSING,
    corr_threshold=CORRELATION_THRESHOLD
):

    """
    Feature screening is based ONLY on the training period.

    Importantly, no test observations influence feature selection.
    """

    X_train = X_train.copy()
    X_test = X_test.copy()

    # -------------------------------------------------------------------------
    # Remove infinite values
    # -------------------------------------------------------------------------

    X_train = X_train.replace(
        [np.inf, -np.inf],
        np.nan
    )

    X_test = X_test.replace(
        [np.inf, -np.inf],
        np.nan
    )

    # -------------------------------------------------------------------------
    # Missingness based ONLY on training
    # -------------------------------------------------------------------------

    missing_rate = (
        X_train.isna().mean()
    )

    keep = missing_rate[
        missing_rate <= max_missing
    ].index.tolist()

    X_train = X_train[keep]
    X_test = X_test[keep]

    # -------------------------------------------------------------------------
    # Remove constant features
    # -------------------------------------------------------------------------

    nunique = X_train.nunique()

    keep = nunique[
        nunique > 1
    ].index.tolist()

    X_train = X_train[keep]
    X_test = X_test[keep]

    # -------------------------------------------------------------------------
    # Remove duplicate columns
    # -------------------------------------------------------------------------

    duplicate_mask = (
        X_train.T
        .duplicated()
    )

    duplicate_cols = (
        X_train.T.index[
            duplicate_mask
        ]
    )

    X_train = X_train.drop(
        columns=duplicate_cols,
        errors="ignore"
    )

    X_test = X_test.drop(
        columns=duplicate_cols,
        errors="ignore"
    )

    # -------------------------------------------------------------------------
    # High correlation filter
    #
    # This is deliberately conservative.
    # -------------------------------------------------------------------------

    if X_train.shape[1] > 1:

        corr = (
            X_train
            .corr()
            .abs()
        )

        upper = corr.where(
            np.triu(
                np.ones(
                    corr.shape
                ),
                k=1
            ).astype(bool)
        )

        drop_cols = [
            column
            for column in upper.columns
            if any(
                upper[column]
                > corr_threshold
            )
        ]

        X_train = X_train.drop(
            columns=drop_cols,
            errors="ignore"
        )

        X_test = X_test.drop(
            columns=drop_cols,
            errors="ignore"
        )

    return X_train, X_test


