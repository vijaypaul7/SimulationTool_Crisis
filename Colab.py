def find_column(df, patterns):
    """Find the first column containing one of the supplied patterns."""
    for col in df.columns:
        col_lower = col.lower()
        for pattern in patterns:
            if pattern.lower() in col_lower:
                return col
    return None


def safe_numeric(series):
    """Convert to numeric and replace +/- infinity with NaN."""
    return pd.to_numeric(series, errors="coerce").replace([np.inf, -np.inf], np.nan)


def evaluate(y_true, y_pred, model_name, target_name, feature_set):
    """Calculate standard out-of-sample metrics."""
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    return {
        "target": target_name,
        "feature_set": feature_set,
        "model": model_name,
        "n_test": len(y_true),
        "mae": mean_absolute_error(y_true, y_pred),
        "rmse": np.sqrt(mean_squared_error(y_true, y_pred)),
        "r2": r2_score(y_true, y_pred)
    }


