    # Extrapolator forecast = current price + theta × momentum
    df['extrapolator_forecast'] = df[fuel_col] + theta * df['momentum_trend']

    # Lag the forecast by 1 period (forecast made at t for t+1)
    df['extrapolator_forecast'] = df['extrapolator_forecast'].shift(1)

    return df

