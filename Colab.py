def run_model_suite(
    X_train,
    y_train,
    X_test,
    y_test,
    target_name,
    feature_set_name,
    full_target
):

    results = []
    predictions = {}

    # -------------------------------------------------------------------------
    # Naive
    # -------------------------------------------------------------------------

    naive_pred = np.repeat(
        y_train.iloc[-1],
        len(y_test)
    )

    result = evaluate(
        y_test,
        naive_pred,
        "Naive",
        target_name,
        feature_set_name
    )

    if result is not None:

        results.append(result)

        predictions["Naive"] = naive_pred


    # -------------------------------------------------------------------------
    # Seasonal naive
    # -------------------------------------------------------------------------

    seasonal_pred = (
        seasonal_naive_from_full_history(
            full_target,
            X_test.index,
            season=12
        )
    )

    result = evaluate(
        y_test,
        seasonal_pred,
        "SeasonalNaive",
        target_name,
        feature_set_name
    )

    if result is not None:

        results.append(result)

        predictions[
            "SeasonalNaive"
        ] = seasonal_pred


    # -------------------------------------------------------------------------
    # Feature screening
    # -------------------------------------------------------------------------

    X_train_clean, X_test_clean = (
        screen_features(
            X_train,
            X_test
        )
    )

    print(
        f"    Features retained: "
        f"{X_train_clean.shape[1]}"
    )

    if X_train_clean.shape[1] == 0:

        print(
            "    No usable features."
        )

        return (
            pd.DataFrame(results),
            predictions
        )


    # -------------------------------------------------------------------------
    # Ridge
    # -------------------------------------------------------------------------

    print("    Tuning Ridge...")

    try:

        model, params, cv_score = fit_ridge(
            X_train_clean,
            y_train
        )

        pred = model.predict(
            X_test_clean
        )

        result = evaluate(
            y_test,
            pred,
            "Ridge",
            target_name,
            feature_set_name
        )

        if result is not None:

            result["cv_rmse"] = -cv_score
            result["best_params"] = str(params)

            results.append(result)

            predictions["Ridge"] = pred

    except Exception as e:

        print(
            f"    Ridge failed: {e}"
        )


    # -------------------------------------------------------------------------
    # ElasticNet
    # -------------------------------------------------------------------------

    print("    Tuning ElasticNet...")

    try:

        model, params, cv_score = (
            fit_elasticnet(
                X_train_clean,
                y_train
            )
        )

        pred = model.predict(
            X_test_clean
        )

        result = evaluate(
            y_test,
            pred,
            "ElasticNet",
            target_name,
            feature_set_name
        )

        if result is not None:

            result["cv_rmse"] = -cv_score
            result["best_params"] = str(params)

            results.append(result)

            predictions[
                "ElasticNet"
            ] = pred

    except Exception as e:

        print(
            f"    ElasticNet failed: {e}"
        )


    # -------------------------------------------------------------------------
    # HistGradientBoosting
    # -------------------------------------------------------------------------

    print(
        "    Tuning HistGradientBoosting..."
    )

    try:

        model, params, cv_score = (
            fit_hist_gradient_boosting(
                X_train_clean,
                y_train
            )
        )

        pred = model.predict(
            X_test_clean
        )

        result = evaluate(
            y_test,
            pred,
            "HistGradientBoosting",
            target_name,
            feature_set_name
        )

        if result is not None:

            result["cv_rmse"] = -cv_score
            result["best_params"] = str(params)

            results.append(result)

            predictions[
                "HistGradientBoosting"
            ] = pred

    except Exception as e:

        print(
            f"    HistGradientBoosting failed: {e}"
        )


    # -------------------------------------------------------------------------
    # XGBoost
    # -------------------------------------------------------------------------

    if USE_XGBOOST:

        print(
            "    Tuning XGBoost..."
        )

        try:

            model, params, cv_score = (
                fit_xgboost(
                    X_train_clean,
                    y_train
                )
            )

            if model is not None:

                pred = model.predict(
                    X_test_clean
                )

                result = evaluate(
                    y_test,
                    pred,
                    "XGBoost",
                    target_name,
                    feature_set_name
                )

                if result is not None:

                    result["cv_rmse"] = -cv_score
                    result["best_params"] = str(params)

                    results.append(result)

                    predictions[
                        "XGBoost"
                    ] = pred

        except Exception as e:

            print(
                f"    XGBoost failed: {e}"
            )


    return (
        pd.DataFrame(results),
        predictions
    )


