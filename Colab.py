norm_2022 = np.linalg.norm(x_jan2022)
norm_2023 = np.linalg.norm(x_jan2023)

# Distance between two economic states
distance = np.linalg.norm(x_jan2022 - x_jan2023)

# Cosine Similarity
dot_prod = np.dot(x_jan2022, x_jan2023)
cosine_sim = dot_prod / (norm_2022 * norm_2023)

