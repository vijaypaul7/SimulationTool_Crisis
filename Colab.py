def get_cv(n):

    """
    Construct an expanding-window CV.

    Never shuffles.
    """

    n_splits = min(
        CV_SPLITS,
        max(2, n // 30)
    )

    return TimeSeriesSplit(
        n_splits=n_splits
    )


