def merge_behavioural_file(main_df, path, columns):
    if not os.path.exists(path):
        print(f"Not found: {path}")
        return main_df
    temp = pd.read_csv(path, index_col=0, parse_dates=True)
    temp.index = pd.to_datetime(temp.index, errors="coerce")
    temp = temp[~temp.index.isna()].sort_index().loc[~temp.index.duplicated()]
    available = [c for c in columns if c in temp.columns]
    if not available:
        print(f"No requested columns found in {path}")
        return main_df
    temp = temp[available].copy()
    for col in available:
        temp[col] = safe_numeric(temp[col])
        main_df[col] = temp[col].reindex(main_df.index)
        print(f"{col}: {main_df[col].notna().sum()} observations")
    return main_df


