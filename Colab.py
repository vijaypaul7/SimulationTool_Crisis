def find_column(df, patterns):
    """
    Find a column using case-insensitive substring matching.
    """
    for col in df.columns:
        col_lower = str(col).lower()

        for pattern in patterns:
            if pattern.lower() in col_lower:
                return col

    return None


def safe_numeric(series):
    """
    Convert to numeric safely.
    """
    if series is None:
        return None

    if series.dtype == "object":
        series = (
            series.astype(str)
            .str.replace(",", "", regex=False)
            .str.replace("%", "", regex=False)
            .str.strip()
        )

    series = pd.to_numeric(series, errors="coerce")

    series = series.replace(
        [np.inf, -np.inf],
        np.nan
    )

    return series


def rmse(y_true, y_pred):
    return np.sqrt(
        mean_squared_error(y_true, y_pred)
    )


def evaluate(
    y_true,
    y_pred,
    model_name,
    target_name,
    feature_set
):
    """
    Safe evaluation.

    Removes invalid prediction pairs before computing metrics.
    """

    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)

    valid = (
        np.isfinite(y_true)
        &
        np.isfinite(y_pred)
    )

    if valid.sum() == 0:
        return None

    yt = y_true[valid]
    yp = y_pred[valid]

    return {
        "target": target_name,
        "feature_set": feature_set,
        "model": model_name,
        "n_test": len(yt),
        "mae": mean_absolute_error(yt, yp),
        "rmse": rmse(yt, yp),
        "r2": r2_score(yt, yp),
        "directional_accuracy": np.mean(
            np.sign(yt) == np.sign(yp)
        )
    }


def seasonal_naive_from_full_history(
    full_target,
    test_index,
    season=12
):
    """
    Correct seasonal-naive forecast.

    IMPORTANT:
    Uses only observations available BEFORE each forecast date.

    For a test date t:
        prediction = target[t - 12 months]

    It does NOT use future test values.
    """

    predictions = []

    full_target = full_target.sort_index()

    for date in test_index:

        previous_date = date - pd.DateOffset(
            months=season
        )

        if previous_date in full_target.index:

            value = full_target.loc[previous_date]

            if pd.notna(value):
                predictions.append(float(value))
            else:
                predictions.append(np.nan)

        else:
            predictions.append(np.nan)

    return np.asarray(predictions)


