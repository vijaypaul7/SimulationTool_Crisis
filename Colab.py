# 21. LSTM - LEAKAGE-SAFE TEMPORAL CONSTRUCTION
# ============================================================

def run_lstm(X_train, y_train, X_test, y_test, lookback=12):
    # Scale using TRAINING DATA ONLY
    scaler_X = StandardScaler()
    scaler_y = StandardScaler()

    X_train_scaled = scaler_X.fit_transform(X_train)
    X_test_scaled = scaler_X.transform(X_test)
    y_train_scaled = scaler_y.fit_transform(y_train.to_numpy().reshape(-1, 1)).flatten()

    # TRAIN SEQUENCES
    X_train_seq = []
    y_train_seq = []
    for i in range(lookback, len(X_train_scaled)):
        X_train_seq.append(X_train_scaled[i-lookback:i])
        y_train_seq.append(y_train_scaled[i])
    X_train_seq = np.asarray(X_train_seq)
    y_train_seq = np.asarray(y_train_seq)

    if len(X_train_seq) < 30:
        return None

    # Validation split (chronological, never shuffled)
    validation_start = int(len(X_train_seq) * 0.8)
    X_fit = X_train_seq[:validation_start]
    y_fit = y_train_seq[:validation_start]
    X_val = X_train_seq[validation_start:]
    y_val = y_train_seq[validation_start:]

    # Build model
    model = Sequential([
        LSTM(32, return_sequences=True, input_shape=(lookback, X_train_seq.shape[2])),
        Dropout(0.20),
        LSTM(16),
        Dropout(0.20),
        Dense(8, activation="relu"),
        Dense(1)
    ])
    model.compile(optimizer=Adam(learning_rate=0.001), loss="mse")

    early_stop = EarlyStopping(monitor="val_loss", patience=15, restore_best_weights=True)
    model.fit(X_fit, y_fit, validation_data=(X_val, y_val), epochs=150, batch_size=16, shuffle=False, callbacks=[early_stop], verbose=0)

    # Test sequences use the LAST LOOKBACK observations FROM TRAINING as historical context
    combined_X = np.vstack([X_train_scaled[-lookback:], X_test_scaled])
    X_test_seq = []
    for i in range(lookback, len(combined_X)):
        X_test_seq.append(combined_X[i-lookback:i])
    X_test_seq = np.asarray(X_test_seq)

    y_pred_scaled = model.predict(X_test_seq, verbose=0).flatten()
    y_pred = scaler_y.inverse_transform(y_pred_scaled.reshape(-1, 1)).flatten()

    assert len(y_pred) == len(y_test)
    return y_pred, model, scaler_X, scaler_y


