def calculate_growth_rates(df, variables, periods=(1, 3, 6, 12)):
    """Calculate growth rates. Rates → pp changes, Levels → % changes."""
    df = df.copy()
    available = {}

    for name, config in variables.items():
        col = config["column"]
        is_rate = config["is_rate"]

        if col not in df.columns:
            print(f"WARNING: Column '{col}' not found for {name}")
            available[name] = None
            continue

        if df[col].isna().all():
            print(f"WARNING: All values are NaN for {name} ({col})")
            available[name] = None
            continue

        if is_rate:
            # Rate variables → percentage-point changes
            for period in periods:
                if period == 1:
                    df[f"{col}_mom_pp"] = df[col].diff()
                else:
                    df[f"{col}_{period}m_pp"] = df[col].diff(period)
            # Also % change for context
            df[f"{col}_mom_pct"] = df[col].pct_change() * 100
            available[name] = {"mom": f"{col}_mom_pp", "unit": "pp", "is_rate": True}
        else:
            # Level/index/price variables → % changes
            for period in periods:
                if period == 1:
                    df[f"{col}_mom_pct"] = df[col].pct_change() * 100
                else:
                    df[f"{col}_{period}m_pct"] = df[col].pct_change(period) * 100
            df[f"{col}_abs_1m"] = df[col].diff()
            available[name] = {"mom": f"{col}_mom_pct", "unit": "%", "is_rate": False}

    return df, available


