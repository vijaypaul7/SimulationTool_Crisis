def calculate_volatility_metrics(df, variables, windows=[3, 6, 12, 24]):
    """
    Calculate comprehensive volatility metrics for all variables.

    FIXES:
    1. Proper scaling for rate variables (percentage point changes)
    2. No artificial scaling by 100
    3. Proper handling of seasonality for spending data
    4. Correct volatility calculation using standard deviation of changes
    """

    df = df.copy()
    volatility_summary = {}

    for name, config in variables.items():
        col = config['column']
        var_type = config.get('type', 'level')  # 'rate', 'level', 'price', 'index'

        if col not in df.columns:
            print(f"WARNING: Column '{col}' not found for {name}")
            continue

        # Check if column has data
        if df[col].isna().all():
            print(f"WARNING: All values are NaN for {name} ({col})")
            continue

        # Calculate appropriate change metric based on variable type
        if var_type == 'rate':
            # For rates (%, already percentage points), use absolute changes (percentage points)
            df[f'{col}_change'] = df[col].diff()
            change_label = 'pp'
        else:
            # For levels/indices/prices, use percentage changes
            df[f'{col}_change'] = df[col].pct_change() * 100
            change_label = '%'

        # Calculate absolute changes (for reference)
        df[f'{col}_abs_change'] = df[col].diff()

        # Rolling volatility metrics - using standard deviation of changes
        for window in windows:
            # Rolling standard deviation of changes - THIS IS THE CORRECT VOLATILITY MEASURE
            min_periods = max(1, window // 2)
            df[f'{col}_vol_{window}m'] = df[f'{col}_change'].rolling(
                window=window,
                min_periods=min_periods
            ).std()

            # Rolling variance (for reference)
            df[f'{col}_var_{window}m'] = df[f'{col}_change'].rolling(
                window=window,
                min_periods=min_periods
            ).var()

            # Rolling range (max - min) for the original series
            df[f'{col}_range_{window}m'] = df[col].rolling(
                window=window,
                min_periods=min_periods
            ).apply(lambda x: x.max() - x.min())

            # Rolling interquartile range
            df[f'{col}_iqr_{window}m'] = df[col].rolling(
                window=window,
                min_periods=min_periods
            ).apply(lambda x: x.quantile(0.75) - x.quantile(0.25))

        # Store summary - using 12-month volatility as the standard metric
        vol_col = f'{col}_vol_12m'
        if vol_col in df.columns and not df[vol_col].isna().all():
            vol_series = df[vol_col].dropna()
            volatility_summary[name] = {
                'mean_vol': vol_series.mean(),
                'max_vol': vol_series.max(),
                'min_vol': vol_series.min(),
                'vol_volatility': vol_series.std(),
                'current_vol': vol_series.iloc[-1] if len(vol_series) > 0 else np.nan,
                'units': change_label,
                'type': var_type
            }

    return df, volatility_summary

