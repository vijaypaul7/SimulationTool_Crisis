def fit_ridge(
    X_train,
    y_train
):

    pipeline = Pipeline([

        (
            "imputer",
            SimpleImputer(
                strategy="median"
            )
        ),

        (
            "scaler",
            RobustScaler()
        ),

        (
            "model",
            Ridge()
        )
    ])

    param_grid = {

        "model__alpha": [
            0.1,
            0.3,
            1,
            3,
            10,
            30,
            100
        ]
    }

    search = GridSearchCV(

        estimator=pipeline,

        param_grid=param_grid,

        scoring="neg_root_mean_squared_error",

        cv=get_cv(len(X_train)),

        n_jobs=-1,

        refit=True
    )

    search.fit(
        X_train,
        y_train
    )

    return (
        search.best_estimator_,
        search.best_params_,
        search.best_score_
    )


