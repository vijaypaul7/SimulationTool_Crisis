def detect_shocks(series, threshold_multiplier=2.5, min_gap=3):
    """Detect shocks using rolling z-score threshold."""
    if len(series) < 12:
        return [], None

    rolling_mean = series.rolling(window=12, min_periods=6).mean()
    rolling_std = series.rolling(window=12, min_periods=6).std()
    z_scores = (series - rolling_mean) / rolling_std
    shock_mask = (z_scores.abs() > threshold_multiplier) & ~z_scores.isna()

    shock_periods = []
    in_shock = False
    start_idx = None

    for i, is_shock in enumerate(shock_mask):
        if is_shock and not in_shock:
            in_shock = True
            start_idx = i
        elif not is_shock and in_shock:
            in_shock = False
            if i - start_idx >= min_gap:
                seg = z_scores.iloc[start_idx:i]
                peak = seg.max() if seg.max() > 0 else seg.min()
                shock_periods.append({
                    "start": series.index[start_idx],
                    "end": series.index[i - 1],
                    "peak_z_score": peak,
                })

    if in_shock:
        seg = z_scores.iloc[start_idx:]
        peak = seg.max() if seg.max() > 0 else seg.min()
        shock_periods.append({
            "start": series.index[start_idx],
            "end": series.index[-1],
            "peak_z_score": peak,
        })

    return shock_periods, z_scores


