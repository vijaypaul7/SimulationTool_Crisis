def calculate_agent_weights(df, lambda_val=0.5):
    """
    Calculate agent weights based on MSFE performance.

    Parameters:
    -----------
    df : DataFrame
        Stage 1 output with MSFE columns
    lambda_val : float
        Selection intensity parameter

    Returns:
    --------
    DataFrame : Data with weight columns added
    """

    df = df.copy()

    # Extract MSFE columns
    msfe_f = df['fundamentalist_msfe_12m']
    msfe_e = df['extrapolator_msfe_12m']

    # Calculate weights using discrete-choice formula
    # w_F = exp(-λ * MSFE_F) / [exp(-λ * MSFE_F) + exp(-λ * MSFE_E)]
    # w_E = 1 - w_F

    # Vectorized calculation
    exp_f = np.exp(-lambda_val * msfe_f)
    exp_e = np.exp(-lambda_val * msfe_e)

    # Avoid division by zero (though with exp() this is unlikely)
    denominator = exp_f + exp_e

    # Calculate Fundamentalist weight
    df['fundamentalist_weight'] = exp_f / denominator

    # Calculate Extrapolator weight
    df['extrapolator_weight'] = 1 - df['fundamentalist_weight']

    # Determine dominant strategy
    df['dominant_strategy'] = np.where(
        df['fundamentalist_weight'] > 0.5,
        'Fundamentalist',
        np.where(df['extrapolator_weight'] > 0.5, 'Extrapolator', 'Equal')
    )

    # Determine dominance strength
    df['dominance_strength'] = np.where(
        df['fundamentalist_weight'] > 0.5,
        df['fundamentalist_weight'],
        df['extrapolator_weight']
    )

    # Strong dominance indicator (>70%)
    df['strong_dominance'] = df['dominance_strength'] > 0.7

    return df

