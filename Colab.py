# 6. HELPER FUNCTION
# ============================================================

def get_episode_data(data, start_date, end_date):

    episode_mask = (
        (data["month"] >= start_date) &
        (data["month"] <= end_date)
    )

    episode_data = data.loc[episode_mask].copy()

    pre_start = start_date - pd.DateOffset(months=12)

    pre_mask = (
        (data["month"] >= pre_start) &
        (data["month"] < start_date)
    )

    pre_data = data.loc[pre_mask].copy()

    return episode_data, pre_data


def calculate_impact(ep_mean, pre_mean, metric):

    if pd.isna(ep_mean) or pd.isna(pre_mean):
        return np.nan

    if metric == "pp":
        return ep_mean - pre_mean

    if metric == "pct":

        if pre_mean == 0:
            return np.nan

        return (
            (ep_mean - pre_mean)
            / pre_mean
            * 100
        )

    return np.nan


def format_impact(value, metric):

    if pd.isna(value):
        return "N/A"

    if metric == "pp":
        return f"{value:+.2f} pp"

    if metric == "pct":
        return f"{value:+.2f}%"

    return f"{value:+.2f}"


