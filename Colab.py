def detect_volatility_regimes(df, vol_col, threshold_multiplier=1.5):
    """
    Detect high-volatility regimes using threshold-based detection.
    """
    series = df[vol_col].dropna()

    if len(series) < 12:
        return None, None

    # Calculate long-term statistics
    long_mean = series.mean()
    long_std = series.std()

    # Define thresholds
    high_threshold = long_mean + (threshold_multiplier * long_std)
    low_threshold = max(0, long_mean - (threshold_multiplier * long_std))  # Can't go below 0

    # Identify high-volatility periods
    high_vol_mask = series > high_threshold

    # Find continuous high-volatility periods
    high_periods = []
    in_high = False
    start_idx = None

    date_index = series.index.tolist()

    for i, is_high in enumerate(high_vol_mask):
        if is_high and not in_high:
            in_high = True
            start_idx = i
        elif not is_high and in_high:
            in_high = False
            start_date = date_index[start_idx]
            end_date = date_index[i-1]
            high_periods.append({
                'start': start_date,
                'end': end_date,
                'duration': i - start_idx,
                'peak_vol': series.iloc[start_idx:i].max()
            })

    if in_high:
        start_date = date_index[start_idx]
        end_date = date_index[-1]
        high_periods.append({
            'start': start_date,
            'end': end_date,
            'duration': len(series) - start_idx,
            'peak_vol': series.iloc[start_idx:].max()
        })

    return high_periods, {
        'mean': long_mean,
        'std': long_std,
        'high_threshold': high_threshold,
        'low_threshold': low_threshold
    }

