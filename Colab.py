def make_dataset(
    df,
    features,
    target
):

    cols = list(
        dict.fromkeys(
            features + [target]
        )
    )

    data = (
        df[cols]
        .replace(
            [np.inf, -np.inf],
            np.nan
        )
        .copy()
    )

    # Target MUST exist.
    data = data.dropna(
        subset=[target]
    )

    # At least one feature must be available.
    feature_cols = [
        c for c in cols
        if c != target
    ]

    if feature_cols:

        data = data.dropna(
            subset=feature_cols,
            how="all"
        )

    return data


